import { compareStrings } from '../order.ts'
import { definitionsFor, termsStandingOn } from '../glossary/index.ts'
import { identityKey } from '../spec-tree/index.ts'
import type { ScenarioIdentity } from '../spec-tree/index.ts'
import type { CapabilitySpec, RequirementSpec, TermSpec } from '../spec-file/index.ts'
import type { ProofSite } from '../test-scan/index.ts'
import { firstSiteByIdentity } from './locate.ts'

/**
 * Renders the tree as the readable site a person reads — the delivery view of the
 * storage/delivery split (`docs/design.md` §4). The committed files hold only titles and
 * locations; this joins them back to the tests, so each requirement shows its description
 * (from the file) and each scenario its Gherkin and current position (from the test).
 *
 * One page per capability plus an index, plus a code page per test file: a scenario's whole
 * point is that its proof is readable, so the site carries the proof too. Each test's page
 * holds one anchored snippet per proof, and every scenario links to the snippet that proves
 * it. The Gherkin and the code are delivered, never stored, so this is not a second copy of
 * behavior.
 *
 * The same capabilities are rendered a second time into one full-spec page. Browsing wants a
 * page per capability; reading the whole promise at once — or handing it to a model — wants
 * one file. Both come from the same render, so the two views cannot say different things.
 */

const GENERATED = '<!-- generated by `proofspec render`; do not edit. The tests are the source of truth. -->'
const INTRO = '_The living spec: every capability, its requirements, and the scenarios that prove them — pulled live from the tests._'
const UNPROVEN = '_Unproven — no test currently proves this scenario._'
const FULL_INTRO = '_The whole spec in one file: every capability, its requirements, and the scenarios that prove them._'
const NO_CAPABILITIES = '_No capabilities yet._'
const VOCAB_INTRO = '_Every term the spec defines, in name order. A requirement uses a term in the exact form it was defined in._'

/** One rendered file: its path within the output directory, and its Markdown. */
export type RenderedPage = {
  readonly path: string
  readonly content: string
}

/** A test file to render as a code page: its path and its whole source. */
export type TestSource = {
  readonly path: string
  readonly source: string
}

export function renderSite(
  specs: readonly CapabilitySpec[],
  sites: readonly ProofSite[],
  tests: readonly TestSource[],
): readonly RenderedPage[] {
  // The proof sites are joined by the same collision rule locate uses, so the position the
  // site shows is the one the rest of the tool agrees on.
  const proven = firstSiteByIdentity(sites)
  // Name order here and nowhere else in the render: the order the spec files happened to be
  // read in must not change the site. Inside a capability the order is the one `spec-file`
  // handed over, kept as given, so the ordering rule stays in one place.
  const capabilities = [...specs].sort((a, b) => compareStrings(a.capability, b.capability))
  const terms = [...specs.flatMap(spec => spec.terms)].sort((a, b) => compareStrings(a.term, b.term))

  const index: RenderedPage = { path: 'index.md', content: renderIndex(capabilities, { vocabulary: terms.length > 0 }) }
  const full: RenderedPage = { path: 'spec.md', content: renderFullPage(capabilities, proven, terms) }
  const vocabulary: RenderedPage[] =
    terms.length > 0 ? [{ path: 'vocabulary.md', content: renderVocabularyPage(terms) }] : []
  const capabilityPages = capabilities.map(capability => ({
    path: `${capability.capability}.md`,
    content: renderCapabilityPage(capability, proven),
  }))
  return [index, full, ...vocabulary, ...capabilityPages, ...renderCodePages(sites, tests)]
}

function renderIndex(
  capabilities: readonly CapabilitySpec[],
  withVocabulary: { readonly vocabulary: boolean },
): string {
  const nav =
    capabilities.length === 0
      ? NO_CAPABILITIES
      : ['**Capabilities**', capabilities.map(one => `- [${one.capability}](${one.capability}.md)`).join('\n')].join('\n\n')
  // Linked only when there is one: a spec that defines no terms is rendered exactly as it
  // was before glossaries existed, and an empty vocabulary page is noise on top of that.
  const vocabulary = withVocabulary.vocabulary ? '- [vocabulary](vocabulary.md)' : ''
  const whole = '[Read the whole spec in one page](spec.md)'
  return `${[frontmatter('ProofSpec — living spec'), GENERATED, INTRO, nav, vocabulary, whole].filter(one => one !== '').join('\n\n')}\n`
}

/**
 * The vocabulary as its own page: every term in name order with its definition, and the
 * two directions of its reach — what it leans on, and what a change to it reaches —
 * computed from the definitions on every render. The edges are the definitions' own
 * words, so drawing them here adds no second copy of anything to drift: a definition
 * rewritten is a page re-rendered. The whole-spec page keeps its vocabulary flat, because
 * the compact payload a model reads wants the meanings, not the map.
 */
function renderVocabularyPage(terms: readonly TermSpec[]): string {
  const entries = terms.map(term => {
    const leansOn = definitionsFor([term.definition], terms)
      .map(one => one.term)
      .filter(name => name !== term.term)
    const reaches = [...termsStandingOn([term.term], terms)]
      .filter(name => name !== term.term)
      .sort(compareStrings)
    const reach = [
      leansOn.length > 0 ? `- leans on: ${leansOn.join(', ')}` : '',
      reaches.length > 0 ? `- a change reaches: ${reaches.join(', ')}` : '',
    ].filter(one => one !== '')
    return [`## Term: ${term.term}`, [term.definition, ...reach].join('\n\n')].join('\n\n')
  })
  return `${[frontmatter('ProofSpec — vocabulary'), GENERATED, VOCAB_INTRO, ...entries].join('\n\n')}\n`
}

function renderCapabilityPage(capability: CapabilitySpec, proven: ProvenSites): string {
  const requirements = renderRequirements(capability, { proven, depth: 2 })
  return `${[frontmatter(capability.capability), GENERATED, ...requirements].join('\n\n')}\n`
}

/**
 * Every capability on one page, each under its own heading and its requirements a level
 * deeper than on a capability page. It is the same render as the capability pages, so the
 * whole-spec view cannot say something the per-capability view does not.
 */
function renderFullPage(
  capabilities: readonly CapabilitySpec[],
  proven: ProvenSites,
  vocabulary: readonly TermSpec[],
): string {
  const sections = capabilities.map(capability =>
    [`## Capability: ${capability.capability}`, ...renderRequirements(capability, { proven, depth: 3 })].join('\n\n'),
  )
  // The vocabulary rides along, definitions first: a model handed the one file is handed
  // the meanings along with the promises, in the order a legal document puts them.
  const defined = vocabulary.map(term => [`### Term: ${term.term}`, term.definition].join('\n\n'))
  const headed =
    defined.length > 0 ? [['## Vocabulary', ...defined].join('\n\n'), ...sections] : sections
  const body = headed.length === 0 ? [NO_CAPABILITIES] : headed
  return `${[frontmatter('ProofSpec — full spec'), GENERATED, FULL_INTRO, ...body].join('\n\n')}\n`
}

/** One capability's requirements, rendered at the heading depth the page they sit on wants. */
function renderRequirements(capability: CapabilitySpec, page: PageStyle): readonly string[] {
  return capability.requirements.map(requirement =>
    renderRequirement(requirement, { ...page, capability: capability.capability }),
  )
}

function renderRequirement(requirement: RequirementSpec, section: Section): string {
  const scenarios = requirement.scenarios.map(scenario =>
    renderScenario({ capability: section.capability, requirement: requirement.requirement, scenario: scenario.scenario }, section),
  )
  const heading = `${'#'.repeat(section.depth)} Requirement: ${requirement.requirement}`
  return [heading, requirement.description, ...scenarios].join('\n\n')
}

function renderScenario(identity: ScenarioIdentity, section: Section): string {
  const { proven } = section
  const heading = `${'#'.repeat(section.depth + 1)} Scenario: ${identity.scenario}`
  const site = proven.get(identityKey(identity))
  if (site === undefined) {
    // Recorded but no test proves it: the spec has drifted. Show it rather than drop it, so
    // the reader sees the gap instead of a page that silently omits a promise.
    return [heading, UNPROVEN].join('\n\n')
  }
  // The location links to the anchored snippet that proves this scenario. The fragment is the
  // slug of the scenario title — the same one the code page's heading gets — so the anchor
  // reads as the scenario, not a bare line number, and the reader lands on the proof.
  const location = `[${site.file}:${site.line}](${codePagePath(site.file)}#${slugOf(site.scenario)})`
  if (site.steps.length === 0) return [heading, location].join('\n\n')
  const steps = site.steps.map(step => `- **${step.keyword}** ${step.text}`).join('\n')
  return [heading, location, steps].join('\n\n')
}

// --- code pages --------------------------------------------------------------

function renderCodePages(sites: readonly ProofSite[], tests: readonly TestSource[]): readonly RenderedPage[] {
  const byFile = sitesByFile(sites)
  return [...tests]
    .filter(test => byFile.has(test.path))
    .sort((a, b) => compareStrings(a.path, b.path))
    .map(test => ({ path: codePagePath(test.path), content: renderCodePage(test, byFile.get(test.path)!) }))
}

function renderCodePage(test: TestSource, fileSites: readonly ProofSite[]): string {
  const lines = test.source.split('\n')
  const snippets = [...fileSites].sort((a, b) => a.line - b.line).map(site => renderSnippet(site, lines))
  return `${[frontmatter(test.path), GENERATED, ...snippets].join('\n\n')}\n`
}

function renderSnippet(site: ProofSite, lines: readonly string[]): string {
  // The scenario title is the heading, so its anchor reads as the scenario a reader clicked.
  // Then the Gherkin, then the proving lines: the claim sits right above its proof, so a reader
  // can judge whether the test does what the claim says — the whole reason to co-locate them.
  const snippet = lines.slice(site.line - 1, site.endLine).join('\n')
  const fence = ['```ts', snippet, '```'].join('\n')
  const parts = [`## ${site.scenario}`, `\`${site.file}:${site.line}\``]
  if (site.steps.length > 0) parts.push(site.steps.map(step => `- **${step.keyword}** ${step.text}`).join('\n'))
  parts.push(fence)
  return parts.join('\n\n')
}

/** Where a test file's code page is written, and so where a scenario's link must point. */
function codePagePath(file: string): string {
  return `${file}.md`
}

/**
 * The heading slug Quartz gives a title, so a scenario's link can target its snippet. Matches
 * github-slugger for the plain-English titles the tests carry: lower-case, drop punctuation,
 * spaces to hyphens. A code page's scope is the file, not the requirement, so two scenarios
 * sharing a title under different requirements would collide there — `guard` allows that, and
 * no title in this repo does it. If one ever does, this is where the anchor stops being stable.
 */
function slugOf(title: string): string {
  return title.toLowerCase().replace(/[^\w\- ]+/g, '').replace(/ /g, '-')
}

/** The proof sites in each test file, so its code page can show one snippet per proof. */
function sitesByFile(sites: readonly ProofSite[]): ReadonlyMap<string, readonly ProofSite[]> {
  const byFile = new Map<string, ProofSite[]>()
  for (const site of sites) {
    const held = byFile.get(site.file) ?? []
    held.push(site)
    byFile.set(site.file, held)
  }
  return byFile
}

/** A YAML frontmatter block naming the page, so a static-site renderer titles it. */
function frontmatter(title: string): string {
  return `---\ntitle: ${title}\n---`
}

/** Each recorded scenario's proof site, or absent when no test proves it. */
type ProvenSites = ReadonlyMap<string, ProofSite>

/**
 * How deep a page nests what it shows. A capability page heads its requirements at `##`; the
 * full-spec page spends that level on the capability, so its requirements sit one deeper.
 */
type PageStyle = {
  readonly proven: ProvenSites
  readonly depth: 2 | 3
}

/** A page's style, plus the capability the requirement being rendered belongs to. */
type Section = PageStyle & { readonly capability: string }
